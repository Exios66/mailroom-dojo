"""The workspace glossary: terms with definitions, aliases, cross-references and their source.

``data/glossary.yaml`` holds ``terms: [{term, definition, aliases, see_also, source}]``.
Loading checks that every definition and source is non-empty, that no term or alias repeats
(ignoring case), and that every ``see_also`` names a term exactly as written. A malformed file
raises :class:`~mailroom_common.errors.ConfigError`. :func:`render_glossary` produces the
committed ``docs/glossary.md``.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from mailroom_common.errors import ConfigError
from mailroom_common.yamlio import load_yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from mailroom_dictionaries.dictionary import DATA_DIR

__all__ = ["GLOSSARY_PATH", "Glossary", "Term", "load_glossary", "render_glossary"]

GLOSSARY_PATH = DATA_DIR / "glossary.yaml"


class _TermSpec(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    term: str
    definition: str
    aliases: list[str] = Field(default_factory=list)
    see_also: list[str] = Field(default_factory=list)
    source: str


class _GlossarySpec(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    terms: list[_TermSpec]


@dataclass(frozen=True)
class Term:
    term: str
    definition: str
    aliases: tuple[str, ...]
    see_also: tuple[str, ...]
    source: str


@dataclass(frozen=True)
class Glossary:
    """Terms sorted case-insensitively by name."""

    terms: tuple[Term, ...]


def load_glossary(path: str | Path = GLOSSARY_PATH) -> Glossary:
    """Load and validate a glossary file."""
    source = str(path)
    raw = load_yaml(path)
    try:
        spec = _GlossarySpec.model_validate(raw)
    except ValidationError as exc:
        problems = "; ".join(
            f"{'.'.join(str(part) for part in error['loc']) or '<root>'}: {error['msg']}"
            for error in exc.errors()
        )
        raise ConfigError(f"invalid glossary file: {problems}", source=source) from exc
    if not spec.terms:
        raise ConfigError("glossary has no terms", source=source)
    claimed: dict[str, str] = {}
    for item in spec.terms:
        for field in ("term", "definition", "source"):
            if not getattr(item, field).strip():
                raise ConfigError(f"term {item.term!r}: {field} is empty", source=source)
        for name in (item.term, *item.aliases):
            folded = name.strip().casefold()
            if not folded:
                raise ConfigError(f"term {item.term!r}: an alias is empty", source=source)
            if folded in claimed:
                raise ConfigError(
                    f"term {item.term!r}: {name!r} repeats {claimed[folded]!r} (case-insensitive)",
                    source=source,
                )
            claimed[folded] = name
    names = {item.term for item in spec.terms}
    for item in spec.terms:
        for target in item.see_also:
            if target == item.term:
                raise ConfigError(f"term {item.term!r}: see_also names the term itself", source=source)
            if target not in names:
                raise ConfigError(
                    f"term {item.term!r}: see_also {target!r} is not a term (write it exactly as the term)",
                    source=source,
                )
    terms = sorted(
        (Term(t.term, t.definition, tuple(t.aliases), tuple(t.see_also), t.source) for t in spec.terms),
        key=lambda t: t.term.casefold(),
    )
    return Glossary(tuple(terms))


def _anchor(term: str) -> str:
    """The heading anchor GitHub generates for ``## term``."""
    return re.sub(r"[^\w\- ]", "", term.strip().lower()).replace(" ", "-")


def render_glossary(glossary: Glossary) -> str:
    """The Markdown page for ``glossary``, ending in one newline."""
    lines = [
        "<!-- Generated by packages/dictionaries/scripts/render_glossary.py from",
        "     packages/dictionaries/src/mailroom_dictionaries/data/glossary.yaml. Do not edit by hand. -->",
        "",
        "# Glossary",
        "",
        "Terms used across the Mailroom workspace. Each entry names the source it is taken from.",
    ]
    for term in glossary.terms:
        lines += ["", f"## {term.term}", "", " ".join(term.definition.split())]
        if term.aliases:
            lines += ["", "Also called: " + ", ".join(term.aliases) + "."]
        if term.see_also:
            links = ", ".join(f"[{name}](#{_anchor(name)})" for name in term.see_also)
            lines += ["", f"See also: {links}."]
        lines += ["", f"Source: {term.source}"]
    return "\n".join(lines) + "\n"
